"""Simple Google Translate-style Streamlit interface for local NLLB translation."""
import streamlit as st

from mt_config import BASE_MODEL_DIR, FINETUNED_DIR, SRC_LANG, TGT_LANG
from translation_engine import TranslationEngine, model_files_exist

st.set_page_config(page_title="Easy Lang", page_icon="🌐", layout="centered")
st.title("🌐 Easy Lang")
st.caption("Private offline translation · Powered by your local NLLB model")

@st.cache_resource(show_spinner=False)
def get_engine():
    return TranslationEngine()

engine = get_engine()
base_ready = model_files_exist(BASE_MODEL_DIR)
fine_ready = model_files_exist(FINETUNED_DIR)

if not base_ready and not fine_ready:
    st.warning("The translation model is not installed on this computer yet.")
    st.code("pip install -r requirements.txt\npython download_model.py\npython -m streamlit run app.py")
    st.stop()

try:
    languages = engine.languages()
except Exception as exc:
    st.error(f"Could not read the local model: {exc}")
    st.stop()

labels = {item["code"]: item["label"] for item in languages}
codes = list(labels)
english = "eng_Latn" if "eng_Latn" in labels else codes[0]
hindi = "hin_Deva" if "hin_Deva" in labels else codes[min(1, len(codes)-1)]

if "source_code" not in st.session_state:
    st.session_state.source_code = english
if "target_code" not in st.session_state:
    st.session_state.target_code = hindi
if "source_text" not in st.session_state:
    st.session_state.source_text = ""
if "translated_text" not in st.session_state:
    st.session_state.translated_text = ""

def clear_translation():
    st.session_state.source_text = ""
    st.session_state.translated_text = ""

left, right = st.columns(2)
with left:
    source_mode = st.radio("From", ["Detect language", "Choose language"], horizontal=True, key="source_mode")
    if source_mode == "Choose language":
        st.selectbox("Source language", codes, format_func=lambda code: labels[code], key="source_code")
    else:
        st.caption("The app will detect the source language from your text.")
with right:
    st.selectbox("To", codes, format_func=lambda code: labels[code], key="target_code")

st.text_area("Enter text", key="source_text", height=190, max_chars=10000, placeholder="Type or paste text here…")
st.caption(f"{len(st.session_state.source_text)} / 10,000 characters")

col_button, col_clear = st.columns([3, 1])
with col_button:
    translate_clicked = st.button("Translate", type="primary", use_container_width=True)
with col_clear:
    st.button("Clear", use_container_width=True, on_click=clear_translation)

if translate_clicked:
    text = st.session_state.source_text.strip()
    if not text:
        st.warning("Enter some text first.")
    else:
        source_code = st.session_state.source_code
        if st.session_state.source_mode == "Detect language":
            with st.spinner("Detecting language…"):
                detected = engine.detect(text)
            if not detected:
                st.error("I couldn't confidently detect this language. Choose it manually.")
                st.stop()
            source_code = detected["code"]
            st.info(f"Detected: {detected['label']}")
        if source_code == st.session_state.target_code:
            st.session_state.translated_text = text
        else:
            try:
                with st.spinner("Translating with the local NLLB model…"):
                    result = engine.translate(text, source_code, st.session_state.target_code, 4)
                st.session_state.translated_text = result["translation"]
                st.session_state.last_model = result["model"]
            except Exception as exc:
                st.error(f"Translation failed: {exc}")

st.subheader("Translation")
st.text_area("Translated text", key="translated_text", height=190, disabled=True)
if st.session_state.translated_text:
    st.caption("Translation was generated by the model installed on this computer.")
    st.download_button("Download translation", st.session_state.translated_text, file_name="translation.txt", mime="text/plain")
